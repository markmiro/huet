import {
  amountParam,
  baseRules,
  hueDecls,
  hueNames,
  hueParams,
  rootBlock,
  type CssInJs,
  type ThemesOption,
} from "./css.ts";
import { AMOUNTS, ROOTS, type Root } from "./engine.ts";
import { createTheme, defaultTheme, type Theme, type ThemeInput } from "./theme.ts";

/** Serializes CSS-in-JS, flattening `&` selectors and nested at-rules. */
export function serialize(selector: string, body: CssInJs, indent = ""): string {
  const decls: string[] = [];
  const nested: string[] = [];
  for (const [key, value] of Object.entries(body)) {
    if (typeof value === "string") {
      decls.push(`${indent}  ${key}: ${value};`);
    } else if (key.startsWith("@")) {
      nested.push(`${indent}${key} {\n${serialize(selector, value, indent + "  ")}${indent}}\n`);
    } else {
      nested.push(serialize(key.replaceAll("&", selector), value, indent));
    }
  }
  const own = decls.length ? `${indent}${selector} {\n${decls.join("\n")}\n${indent}}\n` : "";
  return own + nested.join("");
}

function serializeRules(rules: CssInJs): string {
  return Object.entries(rules)
    .map(([key, value]) => {
      if (typeof value === "string") throw new Error(`Unexpected top-level declaration ${key}`);
      if (key.startsWith("@property")) {
        const body = Object.entries(value).map(([k, v]) => `  ${k}: ${v};`).join("\n");
        return `${key} {\n${body}\n}\n`;
      }
      return serialize(key, value);
    })
    .join("");
}

const cls = (name: string) => `.${name.replaceAll("%", "\\%")}`;
/** Class specificity, like Tailwind utilities, so CSS resets such as `button { background: none }` don't win. */
const any = (selectors: string[]) => `:is(${selectors.join(", ")})`;

/**
 * A complete stylesheet with every Huet class, for projects without Tailwind.
 * Variants like `hover:` need Tailwind; everything else works the same.
 */
export function buildCss(input: Theme | ThemeInput = defaultTheme, options: ThemesOption = {}): string {
  const theme = createTheme(input);
  const parts = [
    `/* Huet: contrast-based color utilities. Generated by buildCss(). */\n`,
    serializeRules(baseRules(theme, options)),
  ];
  const hues: (string | null)[] = [null, ...hueNames(theme)];

  for (const root of ROOTS as readonly Root[]) {
    const all: string[] = [];
    for (const hue of hues) {
      const group = AMOUNTS.map((amount) => cls(`${root}-${hue === null ? "" : `${hue}-`}${amount}%`));
      all.push(...group);
      const params = hueParams(root, hue);
      if (Object.keys(params).length) parts.push(serialize(any(group), params));
      AMOUNTS.forEach((amount, i) => parts.push(serialize(group[i], amountParam(root, amount))));
    }
    parts.push(serialize(any(all), rootBlock(root)));
  }

  const hueClasses = hueNames(theme).map((hue) => cls(`hue-${hue}`));
  hueNames(theme).forEach((hue, i) => parts.push(serialize(hueClasses[i], hueDecls(hue))));
  parts.push(serialize(any(hueClasses), rootBlock("text")));

  return parts.join("");
}
