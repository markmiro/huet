#!/usr/bin/env node
// Writes src/core/tailwind-utilities.css: a Tailwind utility for every explicit-amount
// class, so variants such as hover:, md: and [&>svg]: work on them. Tailwind emits
// only the utilities a project uses. Rerun after changing the class vocabulary;
// a unit test fails while the file is out of date.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const ramps = [undefined, "gray", "red", "yellow", "green", "blue", "purple", "white"];
const properties = { text: "color", border: "border-color", outline: "outline-color" };
export function utilitiesCss() {
  const lines = [
    "/* Generated by scripts/tailwind-utilities.mjs. Do not edit. */",
    "/* A background utility selects one of the states mountTheme computed for the element.",
    "   The others read the color mountTheme computed for that class. */",
  ];
  for (const property of ["bg", "text", "border", "outline", "bg/text", "bg/border", "bg/outline"])
    ramps.forEach((ramp, i) => {
      for (let amount = 0; amount <= 100; amount++) {
        const name = `huet-${property}-${ramp ? ramp + "-" : ""}${amount}`;
        const body = property === "bg"
          ? `--huet-state: ${i * 101 + amount};`
          : `${properties[property.replace("bg/", "")]}: var(--${name.replace("/", "-")});`;
        lines.push(`@utility ${name.replace("/", "\\/")} { ${body} }`);
      }
    });
  return lines.join("\n") + "\n";
}
if (process.argv[1] === fileURLToPath(import.meta.url))
  await writeFile(new URL("../src/core/tailwind-utilities.css", import.meta.url), utilitiesCss());
